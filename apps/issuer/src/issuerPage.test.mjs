import test from "node:test";
import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { createServer } from "vite";

test("正式应用按钮可创建住宅和债权并走到各自发行准备", async () => {
  const dom = new JSDOM("<!doctype html><html><body><div id='root'></div></body></html>", {
    url: "http://issuer-module01-test.invalid/",
  });
  const previous = {};
  for (const name of ["window", "document", "navigator", "localStorage", "sessionStorage", "HTMLElement", "Event", "MouseEvent"]) {
    previous[name] = globalThis[name];
    Object.defineProperty(globalThis, name, { configurable: true, value: name === "window" ? dom.window : dom.window[name] });
  }
  globalThis.IS_REACT_ACT_ENVIRONMENT = true;
  const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom" });
  let root;
  try {
    const { default: App } = await vite.ssrLoadModule("/src/App.tsx");
    const { createElement, act } = await import("react");
    const { createRoot } = await import("react-dom/client");
    root = createRoot(document.getElementById("root"));
    await act(async () => { root.render(createElement(App)); });
    const normalized = (value) => value.replace(/\s+/g, "");
    const findButton = (text, scope = document) => {
      const button = [...scope.querySelectorAll("button")].find((item) => normalized(item.textContent) === normalized(text));
      if (!button) throw new Error(`找不到按钮「${text}」；当前按钮：${[...scope.querySelectorAll("button")].map((item) => normalized(item.textContent)).filter(Boolean).join("、")}`);
      return button;
    };
    const click = async (element) => { await act(async () => { element.click(); }); };
    const clickButton = async (text, scope) => click(findButton(text, scope));
    const openDemo = async () => click([...document.querySelectorAll("button")].find((item) => item.textContent.includes("演示控制台")));
    const clickDemoStep = async (text) => {
      const steps = [...document.querySelectorAll(".demo-console .mock-step-list button")];
      const step = steps.find((item) => item.querySelector("b")?.textContent === text);
      if (!step) throw new Error(`找不到演示步骤：${text}；当前步骤：${steps.map((item) => item.querySelector("b")?.textContent).join("、")}`);
      await click(step);
    };
    const closeDemo = async () => click(document.querySelector(".demo-head button"));
    const setField = async (labelText, value) => {
      const label = [...document.querySelectorAll("label")].find((item) => normalized(item.querySelector("span")?.textContent || "").includes(normalized(labelText)));
      if (!label) throw new Error(`找不到字段「${labelText}」`);
      const field = label.querySelector("input,select,textarea");
      if (!field) throw new Error(`字段「${labelText}」没有输入控件`);
      await act(async () => {
        const setter = Object.getOwnPropertyDescriptor(Object.getPrototypeOf(field), "value")?.set;
        setter.call(field, value);
        field.dispatchEvent(new dom.window.Event(field.tagName === "SELECT" ? "change" : "input", { bubbles: true }));
      });
    };
    const setPublicPermission = async (label) => {
      const field = document.querySelector(`select[aria-label="${label}"]`);
      assert.ok(field, `找不到公开权限：${label}`);
      await act(async () => {
        field.value = "公开";
        field.dispatchEvent(new dom.window.Event("change", { bubbles: true }));
      });
    };
    assert.match(document.body.textContent, /工作台首页/);
    const button = [...document.querySelectorAll("button")].find((item) => item.textContent.includes("演示控制台"));
    assert.ok(button);
    await click(button);
    assert.match(document.body.textContent, /KYB 审核模拟/);
    await clickButton("已通过", document.querySelector(".demo-console"));
    await clickButton("Standard", document.querySelector(".demo-console"));
    await closeDemo();
    await clickButton("投资者门户");
    await setField("网站展示名称", "星河资产投资者门户");
    await setField("企业专属 URL 前缀", "galaxy-assets");
    await clickButton("保存配置");
    await clickButton("资产与发行");
    await clickButton("创建资产");
    assert.match(document.body.textContent, /创建资产/);
    await clickButton("填充示例空字段");
    for (const item of [...document.querySelectorAll(".file-upload-field button")]) await click(item);
    await clickButton("保存资产草稿");
    const saved = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    assert.equal(saved.assets.length, 1);
    assert.equal(saved.assets[0].value, 250000);
    assert.equal(saved.assets[0].details.appraisalCny, "1900000");
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    await click(document.querySelector("table tbody tr"));
    await clickButton("完成资料检查");
    assert.equal(JSON.parse(localStorage.getItem("rwa-issuer-state-v4")).assets[0].status, "Ready");
    await clickButton("配置该资产的权益结构");
    await clickButton("填充示例空条款");
    await click([...document.querySelectorAll(".file-upload-field button")][0]);
    await setPublicPermission("权益文件公开权限");
    await clickButton("保存权益草稿");
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    await clickButton("权益结构");
    await click(document.querySelector("table tbody tr"));
    await clickButton("完成权益检查");
    assert.equal(JSON.parse(localStorage.getItem("rwa-issuer-state-v4")).instruments[0].status, "Ready");
    await clickButton("资产管理");
    await click(document.querySelector("table tbody tr"));
    await clickButton("新建该资产的 Offering");
    await setField("Offering 名称", "朝阳住宅租金收益参与权首期");
    await setField("投资者展示摘要", "住宅租金收益参与权 Mock 首期");
    await setField("主要发行风险", "租金可能波动，投资可能损失；不承诺收益。");
    await setField("发行 Token 份数", "25000");
    await setField("每 Token 价格 U", "10");
    await setField("单笔最低认购金额 U", "1000");
    await click([...document.querySelectorAll(".file-upload-field button")][0]);
    await setPublicPermission("发行文件公开权限");
    await clickButton("保存 Offering 草稿");
    const draft = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    assert.equal(draft.projects.length, 1);
    assert.equal(draft.offerings[0].tokens * draft.offerings[0].price, 250000);
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    await clickButton("发行管理");
    await click(document.querySelector("table tbody tr"));
    await clickButton("确认发行并运行准入检查");
    await clickButton("运行检查并确认");
    const confirmed = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    const { confirmIssuerOffering } = await vite.ssrLoadModule("/src/issuerModule01.ts");
    assert.equal(confirmed.offerings[0].confirmed, true, confirmIssuerOffering(confirmed, confirmed.offerings[0].id, confirmed.offerings[0].revision || 1, new Date().toISOString()).error);
    assert.equal(confirmed.instruments[0].used, 25000);
    await clickButton("进入发行准备");
    assert.match(document.body.textContent, /七组发行准备检查/);
    assert.match(window.location.pathname, /issuance-readiness/);
    await act(async () => { root.unmount(); });
    root = createRoot(document.getElementById("root"));
    await act(async () => { root.render(createElement(App)); });
    assert.match(document.body.textContent, /发行准备资料/);
    assert.equal(JSON.parse(localStorage.getItem("rwa-issuer-state-v4")).projects.length, 1);
    await clickButton("资产管理");
    await clickButton("创建资产");
    await setField("资产类别", "债权与应收款");
    assert.match(document.body.textContent, /单笔企业借款债权/);
    await clickButton("填充示例空字段");
    for (const item of [...document.querySelectorAll(".file-upload-field button")]) await click(item);
    await clickButton("保存资产草稿");
    const debtAssetDraft = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    assert.equal(debtAssetDraft.assets.length, 2);
    assert.equal(debtAssetDraft.assets.find((asset) => asset.category === "债权与应收款")?.value, 400000);
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    const debtAssetRow = [...document.querySelectorAll("table tbody tr")].find((row) => row.textContent.includes("华北物流"));
    assert.ok(debtAssetRow);
    await click(debtAssetRow);
    await clickButton("完成资料检查");
    await clickButton("配置该资产的权益结构");
    await clickButton("填充示例空条款");
    await click([...document.querySelectorAll(".file-upload-field button")][0]);
    await setPublicPermission("权益文件公开权限");
    await clickButton("保存权益草稿");
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    await clickButton("权益结构");
    const debtInstrumentRow = [...document.querySelectorAll("table tbody tr")].find((row) => row.textContent.includes("华北物流"));
    assert.ok(debtInstrumentRow);
    await click(debtInstrumentRow);
    await clickButton("完成权益检查");
    const debtInstrument = JSON.parse(localStorage.getItem("rwa-issuer-state-v4")).instruments.find((instrument) => instrument.type === "债权");
    assert.equal(debtInstrument.status, "Ready");
    assert.equal(debtInstrument.terms.interestMethod, "Actual/365 Fixed");
    await clickButton("资产管理");
    await click([...document.querySelectorAll("table tbody tr")].find((row) => row.textContent.includes("华北物流")));
    await clickButton("新建该资产的 Offering");
    await setField("Offering 名称", "华北物流投资者债权首期");
    await setField("投资者展示摘要", "企业借款债权 Mock 发行测试");
    await setField("主要发行风险", "债务人可能违约，债权本息可能无法按时收回。");
    await setField("发行 Token 份数", "4000");
    await setField("每 Token 价格 U", "100");
    await setField("单笔最低认购金额 U", "1000");
    await click([...document.querySelectorAll(".file-upload-field button")][0]);
    await setPublicPermission("发行文件公开权限");
    await clickButton("保存 Offering 草稿");
    const debtDraft = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    assert.equal(debtDraft.projects.length, 2);
    assert.equal(debtDraft.offerings.find((offering) => offering.name.includes("华北物流")).tokens * debtDraft.offerings.find((offering) => offering.name.includes("华北物流")).price, 400000);
    await openDemo();
    await clickDemoStep("扫描当前待处理文件");
    await closeDemo();
    await clickButton("发行管理");
    const debtOfferingRow = [...document.querySelectorAll("table tbody tr")].find((row) => row.textContent.includes("华北物流"));
    assert.ok(debtOfferingRow);
    await click(debtOfferingRow);
    await clickButton("确认发行并运行准入检查");
    await clickButton("运行检查并确认");
    const debtConfirmed = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    const debtOffering = debtConfirmed.offerings.find((offering) => offering.name.includes("华北物流"));
    assert.equal(debtOffering.confirmed, true, confirmIssuerOffering(debtConfirmed, debtOffering.id, debtOffering.revision || 1, new Date().toISOString()).error);
    assert.equal(debtConfirmed.instruments.find((instrument) => instrument.type === "债权").used, 4000);
    await clickButton("进入发行准备");
    assert.match(document.body.textContent, /七组发行准备检查/);
    assert.match(document.body.textContent, /华北物流/);
    await act(async () => { root.unmount(); });
    root = createRoot(document.getElementById("root"));
    await act(async () => { root.render(createElement(App)); });
    const finalState = JSON.parse(localStorage.getItem("rwa-issuer-state-v4"));
    assert.equal(finalState.assets.length, 2);
    assert.equal(finalState.instruments.length, 2);
    assert.equal(finalState.projects.length, 2);
    assert.equal(finalState.offerings.length, 2);
    assert.equal(finalState.offerings.every((offering) => offering.confirmed && offering.confirmationSnapshot), true);
  } finally {
    if (root) {
      const { act } = await import("react");
      await act(async () => { root.unmount(); });
    }
    await vite.close();
    dom.window.close();
    for (const [name, value] of Object.entries(previous)) {
      if (value === undefined) delete globalThis[name];
      else Object.defineProperty(globalThis, name, { configurable: true, value });
    }
    delete globalThis.IS_REACT_ACT_ENVIRONMENT;
  }
});
