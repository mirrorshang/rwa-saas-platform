import assert from 'node:assert/strict';
import test from 'node:test';
import { createServer } from 'vite';

const values = new Map();
globalThis.sessionStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, String(value)), removeItem: key => values.delete(key) };
globalThis.location = { hostname: '127.0.0.1', search: '?demo=1', origin: 'http://127.0.0.1' };
globalThis.window = new EventTarget();

test('Instrument drafts keep immutable versions and reject stale saves', async () => {
  const vite = await createServer({ mode: 'demo', server: { middlewareMode: true }, appType: 'custom' });
  try {
    const demo = await vite.ssrLoadModule('/src/issuerDemo.ts');
    const model = await vite.ssrLoadModule('/src/issuerInstruments.ts');
    assert.equal(demo.beginDemoAuth('single'), true);
    assert.equal(demo.selectDemoTenant('assetco'), true);
    const tenant = demo.getDemoTenant();
    const fields = { ...model.blankInstrumentFields(), name: '版本测试' };
    const first = model.saveInstrument(tenant, fields);
    assert.equal(first.status, 'saved');
    assert.equal(first.record.versions.length, 1);
    assert.equal(model.saveInstrument(tenant, fields, undefined, 0, first.requestId).record.id, first.record.id);
    assert.equal(model.listInstruments(tenant).length, 1);
    const controls = await vite.ssrLoadModule('/src/demoControls.ts');
    controls.useDemoControls.getState().setControl('instrumentSave', 'failed');
    const failed = model.saveInstrument(tenant, { ...fields, name: '失败后重试' });
    assert.equal(failed.status, 'failed');
    assert.equal(model.getInstrumentIntent(tenant).snapshot.name, '失败后重试');
    controls.useDemoControls.getState().setControl('instrumentSave', 'success');
    const retried = model.saveInstrument(tenant, { ...fields, name: '失败后重试' }, undefined, 0, failed.intent.id);
    assert.equal(retried.status, 'saved');
    assert.equal(model.saveInstrument(tenant, fields, undefined, 0, failed.intent.id).record.id, retried.record.id);
    assert.equal(model.listInstruments(tenant).length, 2);
    const second = model.saveInstrument(tenant, { ...fields, name: '第二版' }, first.record.id, 1);
    assert.equal(second.status, 'saved');
    assert.equal(second.record.versions.length, 2);
    assert.equal(second.record.versions[0].fields.name, '版本测试');
    assert.equal(second.record.versions[1].changes[0].after, '第二版');
    assert.equal(model.saveInstrument(tenant, fields, first.record.id, 1).status, 'conflict');
    assert.equal(model.completeInstrument(tenant, first.record.id).status, 'denied');
    assert.equal(model.prepareInstrument(tenant, first.record.id).status, 'saved');
    assert.equal(model.completeInstrument(tenant, first.record.id).status, 'invalid');

    const assets = await vite.ssrLoadModule('/src/issuerAssets.ts');
    const assetFields = { ...assets.blankAssetFields(), name: '测试住宅', category: '房地产', summary: '住宅资产', propertySubtype: 'residential', country: 'HK', city: '香港', address: '示例地址', area: '100', areaBasis: '建筑面积', owner: '测试主体', tenantRelation: '持有', operationStatus: '运营中', residential: { kind: '公寓', totalUnits: '10', occupiedUnits: '8', unitMix: '', rental: '' } };
    sessionStorage.setItem(assets.assetStorageKey, JSON.stringify({ accounts: { 'demo@wdex.example': { assetco: { assets: [{ id: 'asset-1', tenantId: 'assetco', number: 'A-1', state: 'ready', versions: [{ number: 1, fields: assetFields, savedAt: Date.now(), savedBy: 'demo@wdex.example' }] }], intent: null } } } }));
    const equity = { ...model.blankInstrumentFields(), name: '住宅普通股', type: 'equity', assetId: 'asset-1', assetVersion: 1, rightsOwner: '测试持有人', economicSummary: '普通股分红与表决权', equityEntity: '测试主体', equityShare: '10', shareCount: '100', shareRights: '普通股分红及表决', sourceName: '普通股来源', capacityTotal: '100', structureCap: '100', structureCapBasis: '股东名册', rightsPerToken: '0.5' };
    assert.equal(model.tokenMapping(equity).supply, '200');
    assert.equal(model.tokenMapping({ ...equity, type: 'debt', structureCap: '1000', rightsPerToken: '2' }).supply, '500');
    assert.equal(model.tokenMapping({ ...equity, type: 'income', structureCap: '25', rightsPerToken: '0.25' }).supply, '100');
    const created = model.saveInstrument(tenant, { ...equity, debtor: '旧债权字段', incomeSource: '旧收益字段' });
    assert.equal(created.status, 'saved');
    assert.equal(created.record.versions[0].fields.debtor, '');
    assert.equal(created.record.versions[0].fields.incomeSource, '');
    assert.equal(model.getTokenDefinition(tenant, created.record.id).totalSupply, '200');
    assert.equal(model.prepareInstrument(tenant, created.record.id).status, 'saved');
    assert.equal(model.completeInstrument(tenant, created.record.id).status, 'invalid');
    const fileStore = { accounts: { 'demo@wdex.example': { assetco: { records: [{ id: 'file-1', tenantId: 'assetco', versions: [{ number: 1, name: '股权协议.pdf', size: 100, type: 'application/pdf', addedAt: Date.now(), addedBy: 'demo@wdex.example', status: 'received', scan: 'passed' }] }], refs: [{ id: 'ref-1', owner: 'instrument', ownerId: created.record.id, fileId: 'file-1', version: 1, category: '股权法律文件', note: '', linkedAt: Date.now() }] } } } };
    sessionStorage.setItem('wdex-issuer-files', JSON.stringify(fileStore));
    const withLegal = model.saveInstrument(tenant, { ...equity, legalFileRefId: 'ref-1' }, created.record.id, 1);
    assert.equal(withLegal.status, 'saved');
    assert.equal(model.completeInstrument(tenant, created.record.id).status, 'saved');
    assert.equal(assets.changeAssetStatus(tenant, 'asset-1', 'preparing').status, 'saved');
    assert.equal(model.findInstrument(tenant, created.record.id).status, 'preparing');
    const assetStore = JSON.parse(sessionStorage.getItem(assets.assetStorageKey));
    assetStore.accounts['demo@wdex.example'].assetco.assets[0].state = 'ready';
    sessionStorage.setItem(assets.assetStorageKey, JSON.stringify(assetStore));
    assert.equal(model.completeInstrument(tenant, created.record.id).status, 'saved');
    const repo = model.mockCapacityRepository;
    assert.equal(repo.reserve(tenant, created.record.id, 'offering-draft', '20', 'draft'), false);
    assert.equal(repo.reserve(tenant, created.record.id, 'offering-1', '20', 'confirmed'), true);
    assert.equal(repo.reserve(tenant, created.record.id, 'offering-1', '20', 'confirmed'), false);
    assert.equal(repo.commit(tenant, 'offering-1', '5'), true);
    assert.equal(repo.confirm(tenant, 'offering-1', '10'), true);
    assert.equal(repo.recordMint(tenant, 'offering-1', '5'), true);
    assert.deepEqual(model.capacitySummary(tenant, created.record.id), { total: '100', confirmed: '10', reserved: '10', remaining: '80', committed: '0', minted: '5' });
    assert.equal(repo.markUnknown(tenant, 'offering-1'), true);
    assert.equal(repo.release(tenant, 'offering-1'), false);
    assert.equal(model.capacitySummary(tenant, created.record.id).remaining, '80');
    fileStore.accounts['demo@wdex.example'].assetco.records[0].versions[0].scan = 'failed';
    sessionStorage.setItem('wdex-issuer-files', JSON.stringify(fileStore));
    model.recheckInstrumentReady(tenant, created.record.id);
    assert.equal(model.findInstrument(tenant, created.record.id).status, 'preparing');
    assert.equal(model.findInstrument(tenant, created.record.id).versions.length, 2);
    assert.equal(model.findInstrument({ ...tenant, id: 'other-tenant' }, created.record.id), null);
    fileStore.accounts['demo@wdex.example'].assetco.records[0].versions[0].scan = 'passed';
    sessionStorage.setItem('wdex-issuer-files', JSON.stringify(fileStore));
    assert.equal(model.completeInstrument(tenant, created.record.id).status, 'saved');
    sessionStorage.setItem('wdex-issuer-issuance', JSON.stringify({ accounts: { 'demo@wdex.example': { assetco: { offerings: [{ id: 'offering-1', status: 'sandbox-published', versions: [{ fields: { instrumentId: created.record.id } }] }] } } } }));
    assert.equal(model.markInstrumentPublished(tenant, created.record.id, 'wrong-offering').status, 'denied');
    assert.equal(model.markInstrumentPublished(tenant, created.record.id, 'offering-1').status, 'saved');
    assert.equal(model.saveInstrument(tenant, { ...equity, legalFileRefId: 'ref-1', rightsOwner: '变更主体' }, created.record.id, 2).status, 'denied');
    assert.equal(model.changeRightsStatus(tenant, created.record.id, 'suspend').status, 'saved');
    assert.equal(model.changeRightsStatus(tenant, created.record.id, 'resume').status, 'saved');
    assert.equal(model.findInstrument(tenant, created.record.id).status, 'active');
    assert.equal(model.changeRightsStatus(tenant, created.record.id, 'suspend').status, 'saved');
    assert.equal(model.changeRightsStatus(tenant, created.record.id, 'terminate').status, 'saved');
    assert.equal(model.changeRightsStatus(tenant, created.record.id, 'finalize').status, 'denied');
  } finally { await vite.close(); }
});
