import assert from 'node:assert/strict';
import test from 'node:test';
import { createServer } from 'vite';

const values = new Map();
globalThis.sessionStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, String(value)), removeItem: key => values.delete(key) };
globalThis.location = { hostname: '127.0.0.1', search: '?demo=1', origin: 'http://127.0.0.1' };
globalThis.window = new EventTarget();
const email = 'demo@wdex.example';
const account = data => ({ accounts: { [email]: { assetco: data } } });

test('R2-05 readiness, unique task, Sandbox publication and M handoff', async t => {
  const vite = await createServer({ mode: 'demo', server: { middlewareMode: true }, appType: 'custom' });
  try {
    const demo = await vite.ssrLoadModule('/src/issuerDemo.ts');
    const assets = await vite.ssrLoadModule('/src/issuerAssets.ts');
    const rights = await vite.ssrLoadModule('/src/issuerInstruments.ts');
    const files = await vite.ssrLoadModule('/src/issuerFiles.ts');
    const issuance = await vite.ssrLoadModule('/src/issuerIssuance.ts');
    const readiness = await vite.ssrLoadModule('/src/issuerReadiness.ts');
    const controls = await vite.ssrLoadModule('/src/demoControls.ts');
    assert.equal(demo.beginDemoAuth('single'), true);
    assert.equal(demo.selectDemoTenant('assetco'), true);
    const tenant = demo.getDemoTenant();
    const assetFields = { ...assets.blankAssetFields(), name: '测试住宅', category: '房地产', summary: '已建成住宅资产', propertySubtype: 'residential', country: 'HK', city: '香港', address: '示例地址', area: '100', areaUnit: 'm²', areaBasis: '建筑面积', owner: '测试主体', tenantRelation: '持有', operationStatus: '运营中', residential: { kind: '公寓', totalUnits: '10', occupiedUnits: '8', unitMix: '', rental: '' } };
    sessionStorage.setItem(assets.assetStorageKey, JSON.stringify(account({ assets: [{ id: 'asset-ready', tenantId: 'assetco', number: 'A-1', state: 'ready', versions: [{ number: 1, fields: assetFields, savedAt: Date.now(), savedBy: email }] }], intent: null })));
    const equity = { ...rights.blankInstrumentFields(), name: '住宅普通股', type: 'equity', assetId: 'asset-ready', assetVersion: 1, rightsOwner: '测试持有人', economicSummary: '普通股分红与表决', equityEntity: '测试主体', equityShare: '10', shareCount: '100', shareRights: '普通股分红及表决', sourceName: '独立股权来源', capacityTotal: '100', structureCap: '100', structureCapBasis: '股东名册', rightsPerToken: '0.5', risks: '资产、流动性及法律风险。' };
    const right = rights.saveInstrument(tenant, equity);
    assert.equal(right.status, 'saved');
    const instrumentId = right.record.id;
    const docStore = account({ records: [{ id: 'legal', tenantId: 'assetco', versions: [{ number: 1, name: '股权协议.pdf', size: 100, type: 'application/pdf', addedAt: Date.now(), addedBy: email, status: 'received', scan: 'passed' }] }], refs: [{ id: 'legal-ref', owner: 'instrument', ownerId: instrumentId, fileId: 'legal', version: 1, category: '股权法律文件', note: '', linkedAt: Date.now(), visibility: 'eligible' }] });
    sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
    assert.equal(rights.saveInstrument(tenant, { ...equity, legalFileRefId: 'legal-ref' }, instrumentId, 1).status, 'saved');
    assert.equal(rights.prepareInstrument(tenant, instrumentId).status, 'saved');
    assert.equal(rights.completeInstrument(tenant, instrumentId).status, 'saved');
    const created = issuance.createOfferingDraft(tenant, 'asset-ready', instrumentId, 'r2-05-create');
    assert.equal(created.status, 'saved');
    const offeringId = created.record.id;
    await t.test('Draft is blocked; four statuses are generated from source facts', () => {
      const run = readiness.runReadinessChecks(tenant, offeringId);
      assert.equal(run.status, 'saved');
      assert.equal(run.record.checks.length, 7);
      assert.equal(run.record.checks.find(item => item.code === 'P04').status, 'BLOCKED');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'draft-task').status, 'invalid');
      assert.equal(readiness.applyForMChannel(tenant, offeringId).status, 'invalid');
      controls.useDemoControls.getState().setControl('readinessCheck', 'timeout');
      const timed = readiness.runReadinessChecks(tenant, offeringId);
      assert.equal(timed.record.checks.find(item => item.code === 'P06').status, 'UNKNOWN');
      controls.useDemoControls.getState().setControl('readinessCheck', 'ready');
    });
    docStore.accounts[email].assetco.records.push({ id: 'disclosure', tenantId: 'assetco', versions: [{ number: 1, name: '发行条款.pdf', size: 100, type: 'application/pdf', addedAt: Date.now(), addedBy: email, status: 'received', scan: 'passed' }] });
    docStore.accounts[email].assetco.refs.push({ id: 'disclosure-ref', owner: 'offering', ownerId: offeringId, fileId: 'disclosure', version: 1, category: '发行条款', note: '', linkedAt: Date.now(), visibility: 'eligible' });
    docStore.accounts[email].assetco.records.push({ id: 'internal', tenantId: 'assetco', versions: [{ number: 1, name: '内部经营资料.pdf', size: 100, type: 'application/pdf', addedAt: Date.now(), addedBy: email, status: 'received', scan: 'passed' }] });
    docStore.accounts[email].assetco.refs.push({ id: 'internal-ref', owner: 'offering', ownerId: offeringId, fileId: 'internal', version: 1, category: '内部运营资料', note: '', linkedAt: Date.now(), visibility: 'internal' });
    sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
    const fields = { ...issuance.offeringFields(created.record), name: '第一轮发行', maxRights: '20', maxTokens: '40', unitPrice: '2', maxRaise: '80', opensAt: '2030-01-01T00:00', closesAt: '2030-02-01T00:00', minSubscription: '2', maxSubscription: '20', disclosureRefIds: ['disclosure-ref'] };
    assert.equal(issuance.saveOfferingDraft(tenant, offeringId, fields, 1).status, 'saved');
    assert.equal(issuance.confirmOffering(tenant, offeringId, 2).status, 'saved');
    await t.test('Confirmed sources and disclosure preview are tenant scoped', async () => {
      const run = readiness.runReadinessChecks(tenant, offeringId);
      assert.equal(run.status, 'saved');
      assert.deepEqual(run.record.checks.slice(0, 6).map(item => item.status), Array(6).fill('PASS'), run.record.checks.map(item => `${item.code}:${item.reason}`).join('\n'));
      assert.equal(run.record.checks[6].status, 'PENDING');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'without-declaration').status, 'invalid');
      run.record.checks[0].status = 'BLOCKED';
      assert.equal(readiness.latestCheckRun(tenant, offeringId).checks[0].status, 'PASS');
      assert.equal(rights.capacitySummary(tenant, instrumentId).reserved, '20');
      const preview = readiness.investorPreview(tenant, offeringId);
      assert.equal(preview.simulated, true);
      assert.equal(preview.publiclyAvailable, false);
      assert.deepEqual(preview.documents.map(item => item.name), ['发行条款.pdf']);
      assert.equal(readiness.investorPreview({ ...tenant, id: 'issuerco' }, offeringId), null);
      assert.equal(readiness.publicationForOffering({ ...tenant, id: 'issuerco' }, offeringId), null);
      assert.equal(await files.getFilePayload({ ...tenant, id: 'issuerco' }, 'disclosure', 1), null);
      controls.useDemoControls.getState().setControl('readinessRiskGuard', 'blocked');
      assert.equal(readiness.runReadinessChecks(tenant, offeringId).record.checks[4].status, 'BLOCKED');
      controls.useDemoControls.getState().setControl('readinessRiskGuard', 'simulated-ready');
      controls.useDemoControls.getState().setControl('readinessCheck', 'timeout');
      assert.deepEqual(readiness.runReadinessChecks(tenant, offeringId).record.checks.map(item => item.status), Array(7).fill('UNKNOWN'));
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'timeout-task').status, 'invalid');
      controls.useDemoControls.getState().setControl('readinessCheck', 'ready');
      readiness.runReadinessChecks(tenant, offeringId);
    });
    await t.test('declaration is explicit, versioned, and old PASS becomes stale', () => {
      assert.equal(readiness.confirmResponsibility(tenant, offeringId, false).status, 'invalid');
      const declaration = readiness.confirmResponsibility(tenant, offeringId, true);
      assert.equal(declaration.status, 'saved');
      assert.equal(declaration.record.version, readiness.sandboxDeclarationVersion);
      assert.equal(declaration.record.assetVersion, 1);
      assert.equal(declaration.record.disclosureRefs[0].version, 1);
      const run = readiness.runReadinessChecks(tenant, offeringId);
      assert.deepEqual(run.record.checks.map(item => item.status), Array(7).fill('PASS'));
      const stored = JSON.parse(sessionStorage.getItem(readiness.readinessStorageKey));
      const declarations = stored.accounts[email].assetco.declarations;
      declarations.at(-1).version = 'OLD-VERSION';
      sessionStorage.setItem(readiness.readinessStorageKey, JSON.stringify(stored));
      assert.equal(readiness.runReadinessChecks(tenant, offeringId).record.checks[6].status, 'PENDING');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'old-declaration').status, 'invalid');
      declarations.at(-1).version = readiness.sandboxDeclarationVersion;
      sessionStorage.setItem(readiness.readinessStorageKey, JSON.stringify(stored));
      readiness.runReadinessChecks(tenant, offeringId);
      docStore.accounts[email].assetco.records[1].versions.push({ number: 2, name: '发行条款V2.pdf', size: 110, type: 'application/pdf', addedAt: Date.now(), addedBy: email, status: 'received', scan: 'passed' });
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      assert.equal(readiness.latestCheckRun(tenant, offeringId).stale, true);
      assert.equal(readiness.latestCheckRun(tenant, offeringId).checks[4].status, 'UNKNOWN');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'stale-task').status, 'invalid');
      docStore.accounts[email].assetco.records[1].versions.pop();
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      const assetStore = JSON.parse(sessionStorage.getItem(assets.assetStorageKey));
      assetStore.accounts[email].assetco.assets[0].state = 'restricted';
      sessionStorage.setItem(assets.assetStorageKey, JSON.stringify(assetStore));
      assert.equal(readiness.latestCheckRun(tenant, offeringId).stale, true);
      assert.equal(readiness.runReadinessChecks(tenant, offeringId).record.checks[1].status, 'BLOCKED');
      assetStore.accounts[email].assetco.assets[0].state = 'ready';
      sessionStorage.setItem(assets.assetStorageKey, JSON.stringify(assetStore));
      assert.equal(rights.mockCapacityRepository.reserve(tenant, instrumentId, 'capacity-change-fixture', '1', 'confirmed'), true);
      assert.equal(readiness.latestCheckRun(tenant, offeringId).stale, true);
      assert.equal(rights.mockCapacityRepository.release(tenant, 'capacity-change-fixture'), true);
      assert.equal(readiness.runReadinessChecks(tenant, offeringId).record.checks[6].status, 'PASS');
    });
    await t.test('Standard production gates block even Standard subscription', () => {
      const production = readiness.runReadinessChecks(tenant, offeringId, 'production');
      assert.equal(production.record.checks[0].status, 'BLOCKED');
      assert.equal(production.record.checks[5].status, 'BLOCKED');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'real-task', 'production').status, 'invalid');
      assert.equal(readiness.publicationForOffering(tenant, offeringId), null);
    });
    await t.test('one task, no second reservation, verified Sandbox publication snapshot', () => {
      const first = readiness.createExecutionTask(tenant, offeringId, 'intent-one');
      assert.equal(first.status, 'saved');
      assert.equal(first.record.status, 'submitted');
      assert.equal(readiness.createExecutionTask(tenant, offeringId, 'intent-two').record.id, first.record.id);
      assert.equal(issuance.cancelConfirmedOffering(tenant, offeringId, '已有执行任务').status, 'denied');
      docStore.accounts[email].assetco.refs.find(item => item.id === 'disclosure-ref').visibility = 'internal';
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      assert.equal(readiness.executeSandboxTask(tenant, first.record.id).status, 'conflict');
      assert.equal(readiness.taskForOffering(tenant, offeringId).status, 'pending-admission');
      assert.equal(readiness.contractForInstrument(tenant, instrumentId), null);
      docStore.accounts[email].assetco.refs.find(item => item.id === 'disclosure-ref').visibility = 'eligible';
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      readiness.runReadinessChecks(tenant, offeringId);
      controls.useDemoControls.getState().setControl('sandboxExecution', 'unknown');
      assert.equal(readiness.executeSandboxTask(tenant, first.record.id).status, 'unknown');
      const originalContractId = readiness.contractForInstrument(tenant, instrumentId).id;
      assert.equal(readiness.executeSandboxTask(tenant, first.record.id).status, 'unknown');
      assert.equal(readiness.reconcileSandboxTask(tenant, first.record.id).status, 'unknown');
      controls.useDemoControls.getState().setControl('sandboxExecution', 'failed');
      assert.equal(readiness.reconcileSandboxTask(tenant, first.record.id).status, 'failed');
      assert.equal(issuance.findOffering(tenant, offeringId).status, 'confirmed');
      controls.useDemoControls.getState().setControl('sandboxExecution', 'success');
      assert.equal(readiness.executeSandboxTask(tenant, first.record.id).status, 'saved');
      assert.equal(readiness.executeSandboxTask(tenant, first.record.id).record.id, first.record.id);
      assert.equal(readiness.taskForOffering(tenant, offeringId).status, 'verified');
      const published = issuance.findOffering(tenant, offeringId);
      assert.equal(published.status, 'published');
      const snapshot = readiness.publicationForOffering(tenant, offeringId);
      assert.equal(snapshot.taskId, first.record.id);
      assert.equal(snapshot.contractId, originalContractId);
      assert.equal(readiness.contractForInstrument(tenant, instrumentId).id, originalContractId);
      assert.equal(snapshot.disclosureRefs[0].version, 1);
      assert.equal(snapshot.riskSummary, '资产、流动性及法律风险。');
      assert.deepEqual(snapshot.riskDisclosureRefs, []);
      snapshot.terms.unitPrice = '999';
      assert.equal(readiness.publicationForOffering(tenant, offeringId).terms.unitPrice, '2');
      docStore.accounts[email].assetco.records[1].versions.push({ number: 2, name: '发行条款V2.pdf', size: 110, type: 'application/pdf', addedAt: Date.now(), addedBy: email, status: 'received', scan: 'passed' });
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      assert.deepEqual(readiness.investorPreview(tenant, offeringId).documents.map(item => item.version), [1]);
      docStore.accounts[email].assetco.refs.find(item => item.id === 'disclosure-ref').visibility = 'internal';
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      assert.equal(readiness.investorPreview(tenant, offeringId).documents.length, 0);
      docStore.accounts[email].assetco.refs.find(item => item.id === 'disclosure-ref').visibility = 'eligible';
      docStore.accounts[email].assetco.records[1].versions.pop();
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      assert.equal(published.facts.mintedTokens, '0');
      assert.equal(rights.capacitySummary(tenant, instrumentId).reserved, '20');
      assert.equal(rights.reservationsForOffering(tenant, offeringId).length, 1);
      assert.equal(issuance.recordAuthoritativeOfferingEvent(tenant, offeringId, 'publish', { source: 'readiness', publicationSnapshot: {} }).status, 'denied');
      assert.equal(readiness.sandboxAvailability(tenant, offeringId, Date.parse('2029-12-01T00:00:00+08:00')).eligibleForNewOrder, false);
    });
    await t.test('M application is independent, idempotent and P fixture isolated', () => {
      const first = readiness.applyForMChannel(tenant, offeringId);
      assert.equal(first.status, 'saved');
      assert.equal(first.record.status, 'pending');
      assert.equal(readiness.applyForMChannel(tenant, offeringId).record.id, first.record.id);
      assert.equal(readiness.receivePlatformReviewFixture(tenant, first.record.id, 'approved', '', 'issuer-ui').status, 'denied');
      assert.equal(readiness.receivePlatformReviewFixture(tenant, first.record.id, 'rejected', '资料不足', 'platform-test-fixture').status, 'saved');
      assert.equal(issuance.findOffering(tenant, offeringId).status, 'published');
      assert.equal(readiness.receivePlatformReviewFixture(tenant, first.record.id, 'approved', '', 'platform-test-fixture').record.status, 'approved');
      assert.equal(readiness.receivePlatformReviewFixture(tenant, first.record.id, 'suspended', 'M渠道暂停', 'platform-test-fixture').record.status, 'suspended');
      assert.equal(issuance.findOffering(tenant, offeringId).status, 'published');
    });
    await t.test('overall risk pause blocks channel conditions without deleting M history', () => {
      assert.equal(issuance.pauseOffering(tenant, offeringId, '系统风险', 'system').status, 'saved');
      assert.equal(readiness.sandboxAvailability(tenant, offeringId).eligibleForNewOrder, false);
      assert.equal(readiness.channelApplicationForOffering(tenant, offeringId).status, 'suspended');
      assert.equal(issuance.findOffering(tenant, offeringId).status, 'published');
    });
    await t.test('Standard entitlement still cannot run real production', () => {
      const store = JSON.parse(sessionStorage.getItem('wdex-issuer-demo-store'));
      store.entitlements.find(item => item.tenantId === tenant.id).plan = 'Standard';
      sessionStorage.setItem('wdex-issuer-demo-store', JSON.stringify(store));
      const standard = demo.getDemoTenant();
      assert.equal(standard.plan, 'Standard');
      const run = readiness.runReadinessChecks(standard, offeringId, 'production');
      assert.equal(run.record.checks[0].status, 'BLOCKED');
      assert.equal(run.record.checks[5].status, 'BLOCKED');
      assert.equal(readiness.createExecutionTask(standard, offeringId, 'standard-real', 'production').status, 'invalid');
    });
    await t.test('next round reuses Logical Token and Sandbox Contract; unknown creation returns original task', () => {
      const firstContractId = readiness.contractForInstrument(tenant, instrumentId).id;
      const store = JSON.parse(sessionStorage.getItem(issuance.issuanceStorageKey));
      const firstRound = store.accounts[email].assetco.offerings.find(item => item.id === offeringId);
      firstRound.status = 'completed'; firstRound.pause = undefined; firstRound.facts.obligationsCleared = true;
      sessionStorage.setItem(issuance.issuanceStorageKey, JSON.stringify(store));
      assert.equal(rights.mockCapacityRepository.release(tenant, offeringId), true);
      const second = issuance.createOfferingDraft(tenant, 'asset-ready', instrumentId, 'second-round');
      assert.equal(second.status, 'saved');
      assert.equal(second.project.id, created.project.id);
      docStore.accounts[email].assetco.refs.push({ id: 'second-disclosure-ref', owner: 'offering', ownerId: second.record.id, fileId: 'disclosure', version: 1, category: '发行条款', note: '', linkedAt: Date.now(), visibility: 'eligible' });
      sessionStorage.setItem(files.fileStorageKey, JSON.stringify(docStore));
      const inShanghai = ms => new Date(ms + 8 * 60 * 60 * 1000).toISOString().slice(0, 16);
      const secondFields = { ...issuance.offeringFields(second.record), name: '第二轮发行', maxRights: '10', maxTokens: '20', unitPrice: '2', maxRaise: '40', opensAt: inShanghai(Date.now() - 5 * 60_000), closesAt: inShanghai(Date.now() + 15 * 60_000), minSubscription: '2', maxSubscription: '20', disclosureRefIds: ['second-disclosure-ref'] };
      assert.equal(issuance.saveOfferingDraft(tenant, second.record.id, secondFields, 1).status, 'saved');
      assert.equal(issuance.confirmOffering(tenant, second.record.id, 2).status, 'saved');
      assert.equal(issuance.tokenIdentity(tenant, instrumentId).id, readiness.contractForInstrument(tenant, instrumentId).tokenDefinitionId);
      assert.deepEqual(readiness.runReadinessChecks(tenant, second.record.id).record.checks.slice(0, 6).map(item => item.status), Array(6).fill('PASS'));
      assert.equal(readiness.confirmResponsibility(tenant, second.record.id, true).status, 'saved');
      assert.deepEqual(readiness.runReadinessChecks(tenant, second.record.id).record.checks.map(item => item.status), Array(7).fill('PASS'));
      controls.useDemoControls.getState().setControl('readinessTaskCreate', 'unknown');
      const pending = readiness.createExecutionTask(tenant, second.record.id, 'second-intent');
      assert.equal(pending.status, 'unknown');
      assert.equal(readiness.createExecutionTask(tenant, second.record.id, 'duplicate-intent').record.id, pending.record.id);
      assert.equal(readiness.reconcileSandboxTask(tenant, pending.record.id).status, 'saved');
      assert.equal(readiness.contractForInstrument(tenant, instrumentId).id, firstContractId);
      assert.equal(readiness.contractForInstrument(tenant, instrumentId).taskIds.length, 2);
      assert.notEqual(readiness.publicationForOffering(tenant, second.record.id).id, readiness.publicationForOffering(tenant, offeringId).id);
      assert.equal(readiness.publicationForOffering(tenant, second.record.id).contractId, firstContractId);
      assert.equal(readiness.synchronizeSandboxWindow(tenant, second.record.id).record.status, 'active');
      assert.equal(readiness.sandboxAvailability(tenant, second.record.id).eligibleForNewOrder, true);
      controls.useDemoControls.getState().setControl('readinessRiskGuard', 'blocked');
      assert.equal(readiness.synchronizeSandboxWindow(tenant, second.record.id).record.pause.source, 'system');
      assert.equal(readiness.sandboxAvailability(tenant, second.record.id).eligibleForNewOrder, false);
      assert.equal(rights.capacitySummary(tenant, instrumentId).reserved, '10');
    });
  } finally { await vite.close(); }
});
